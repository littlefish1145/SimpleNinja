void MissingDependencyPrinter::OnMissingDep(Node* node, const std::string& path,
                                            const Rule& generator) {
  std::cout << "Missing dep: " << node->path() << " uses " << path
            << " (generated by " << generator.name() << ")\n";
}

void MissingDependencyPrinter::OnStats(int nodes_processed,
                                       int nodes_missing_deps,
                                       int missing_dep_path_count,
                                       int generated_nodes,
                                       int generator_rules) {
  std::cout << "Processed " << nodes_processed << " nodes.\n";
  if (nodes_missing_deps > 0) {
    std::cout << "Error: There are " << missing_dep_path_count
              << " missing dependency paths.\n";
    std::cout << nodes_missing_deps
              << " targets had depfile dependencies on " << generated_nodes
              << " distinct generated inputs (from " << generator_rules
              << " rules) without a non-depfile dep path to the generator.\n";
    std::cout << "There might be build flakiness if any of the targets listed "
                 "above are built alone, or not late enough, in a clean output "
                 "directory.\n";
  } else {
    std::cout << "No missing dependencies on generated files found.\n";
  }
}

MissingDependencyScanner::MissingDependencyScanner(
    MissingDependencyScannerDelegate* delegate, DepsLog* deps_log, State* state,
    DiskInterface* disk_interface)
    : delegate_(delegate),
      deps_log_(deps_log),
      state_(state),
      disk_interface_(disk_interface),
      missing_dep_path_count_(0) {}

void MissingDependencyScanner::ProcessNode(Node* node) {
  if (!node)
    return;
  Edge* edge = node->in_edge();
  if (!edge)
    return;
  if (!seen_.insert(node).second)
    return;

  for (std::vector<Node*>::iterator in = edge->inputs_.begin();
       in != edge->inputs_.end(); ++in)
    ProcessNode(*in);

  const std::string deps_type = edge->GetBinding("deps");
  if (!deps_type.empty()) {
    DepsLog::Deps* deps = deps_log_ ? deps_log_->GetDeps(node) : NULL;
    if (deps)
      ProcessNodeDeps(node, deps->nodes, deps->node_count);
    return;
  }

  // No `deps` binding: the implicit inputs come from a depfile.  Read it
  // directly rather than going through ImplicitDepLoader, which would splice the
  // discovered nodes into the edge and corrupt the graph we are inspecting.
  const std::string depfile = edge->GetUnescapedDepfile();
  if (depfile.empty())
    return;
  std::string content;
  std::string err;
  if (disk_interface_->ReadFile(depfile, &content, &err) != DiskInterface::Okay)
    return;

  DepfileParser parser;
  if (!parser.Parse(&content, &err))
    return;

  std::vector<Node*> dep_nodes;
  for (std::string_view i : parser.ins_) {
    uint64_t slash_bits;
    size_t len = i.size();
    CanonicalizePath(const_cast<char*>(i.data()), &len, &slash_bits);
    dep_nodes.push_back(
        state_->GetNode(std::string_view(i.data(), len), slash_bits));
  }
  ProcessNodeDeps(node, dep_nodes.data(), static_cast<int>(dep_nodes.size()));
}

void MissingDependencyScanner::ProcessNodeDeps(Node* node, Node** dep_nodes,
                                               int dep_nodes_count) {
  Edge* edge = node->in_edge();
  std::set<Edge*> deplog_edges;
  for (int i = 0; i < dep_nodes_count; ++i) {
    Node* deplog_node = dep_nodes[i];
    // A dep on build.ninja often means "rebuild me when the build is
    // reconfigured", and build.ninja itself is generated by the configure step.
    // The rest of the build already depends on that reconfiguration happening,
    // so report it as found rather than as a missing dependency.
    if (deplog_node->path() == "build.ninja")
      return;
    Edge* deplog_edge = deplog_node->in_edge();
    if (deplog_edge)
      deplog_edges.insert(deplog_edge);
  }

  std::vector<Edge*> missing_deps;
  for (std::set<Edge*>::iterator de = deplog_edges.begin();
       de != deplog_edges.end(); ++de) {
    if (!PathExistsBetween(*de, edge))
      missing_deps.push_back(*de);
  }
  if (missing_deps.empty())
    return;

  std::set<std::string> missing_deps_rule_names;
  for (std::vector<Edge*>::iterator ne = missing_deps.begin();
       ne != missing_deps.end(); ++ne) {
    for (int i = 0; i < dep_nodes_count; ++i) {
      if (dep_nodes[i]->in_edge() == *ne) {
        generated_nodes_.insert(dep_nodes[i]);
        generator_rules_.insert(&(*ne)->rule());
        missing_deps_rule_names.insert((*ne)->rule().name());
        delegate_->OnMissingDep(node, dep_nodes[i]->path(), (*ne)->rule());
      }
    }
  }
  missing_dep_path_count_ += static_cast<int>(missing_deps_rule_names.size());
  nodes_missing_deps_.insert(node);
}

void MissingDependencyScanner::PrintStats() {
  delegate_->OnStats(static_cast<int>(seen_.size()),
                     static_cast<int>(nodes_missing_deps_.size()),
                     missing_dep_path_count_,
                     static_cast<int>(generated_nodes_.size()),
                     static_cast<int>(generator_rules_.size()));
}

bool MissingDependencyScanner::PathExistsBetween(Edge* from, Edge* to) {
  AdjacencyMap::iterator it = adjacency_map_.find(from);
  if (it != adjacency_map_.end()) {
    InnerAdjacencyMap::iterator inner_it = it->second.find(to);
    if (inner_it != it->second.end())
      return inner_it->second;
  } else {
    it = adjacency_map_.insert(std::make_pair(from, InnerAdjacencyMap())).first;
  }

  bool found = false;
  for (size_t i = 0; i < to->inputs_.size(); ++i) {
    Edge* e = to->inputs_[i]->in_edge();
    if (e && (e == from || PathExistsBetween(from, e))) {
      found = true;
      break;
    }
  }
  it->second.insert(std::make_pair(to, found));
  return found;
}
